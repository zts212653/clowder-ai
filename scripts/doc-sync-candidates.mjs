#!/usr/bin/env node
// Daily doc guard candidate list (zero model tokens).
// Lists feature-linked PRs whose feature doc has no follow-up naming the PR,
// BACKLOG rows that disagree with or lag behind their feature doc Status, and
// PRs without any feature id that nobody has disposed of yet.
// Candidates are leads to verify, never verdicts.
//
// Usage:
//   node scripts/doc-sync-candidates.mjs [--days 7] [--ref origin/main] [--no-fetch] [--json] [--update-ledger]
//   node scripts/doc-sync-candidates.mjs --dispose-row F128 --note "row already matches the doc"
// The ledger docs/ops/doc-sync-dispositions.json is read from and written to this
// checkout (run it in the main checkout; publish with pnpm shared:publish).
// Guide: docs/ops/daily-doc-sync.md

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  backlogStatusFinding,
  docCommitsForPr,
  hasDocSyncLine,
  latestChangeByFeature,
  linkPrToFeatures,
  parseBacklogRows,
  parseStatusLine,
  prTouchesFeatureDoc,
} from './lib/doc-sync-candidates.mjs';
import {
  hasCandidates,
  nextOpenPrs,
  normalizeLedger,
  render,
  rowDisposed,
  rowDisposition,
  scanStart,
} from './lib/doc-sync-ledger.mjs';

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const LEDGER = resolve(repoRoot, 'docs/ops/doc-sync-dispositions.json');
const MAX_BUFFER = 512 * 1024 * 1024;
const LIST_LIMIT = 500;
const PR_FIELDS = 'number,title,body,headRefName,mergedAt,mergeCommit';
// Eval verdict PRs are generated by the verdict publisher; their bodies cite
// features but they never change what a feature doc should say.
const GENERATED_TITLE_RE = /^verdict\(/;

function run(cmd, args) {
  return execFileSync(cmd, args, { cwd: repoRoot, encoding: 'utf8', maxBuffer: MAX_BUFFER });
}

/**
 * The row file at `ref`. Home keeps the hand-maintained docs/BACKLOG.md; the public sync drops it
 * and generates docs/ROADMAP.md with the same rows. Same order as check-feature-truth.mjs.
 */
const ROW_FILES = ['docs/BACKLOG.md', 'docs/ROADMAP.md'];
function rowFileAt(ref) {
  const found = ROW_FILES.find((path) => {
    try {
      execFileSync('git', ['cat-file', '-e', `${ref}:${path}`], { cwd: repoRoot, stdio: 'ignore' });
      return true;
    } catch {
      return false;
    }
  });
  if (!found) throw new Error(`Neither ${ROW_FILES.join(' nor ')} exists at ${ref}`);
  return found;
}

function parseArgs(argv) {
  const opts = { days: 7, ref: 'origin/main', fetch: true, json: false, updateLedger: false };
  const takes = { '--days': 'days', '--ref': 'ref', '--dispose-row': 'disposeRow', '--note': 'note' };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (takes[arg]) opts[takes[arg]] = argv[++i];
    else if (arg === '--no-fetch') opts.fetch = false;
    else if (arg === '--json') opts.json = true;
    else if (arg === '--update-ledger') opts.updateLedger = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  opts.days = Number(opts.days);
  if (!Number.isFinite(opts.days) || opts.days <= 0) throw new Error('--days must be a positive number');
  if (opts.disposeRow && !opts.note?.trim()) throw new Error('--dispose-row needs --note "<reason>"');
  return opts;
}

function readLedger() {
  return normalizeLedger(existsSync(LEDGER) ? JSON.parse(readFileSync(LEDGER, 'utf8')) : {});
}

function writeLedger(ledger) {
  writeFileSync(LEDGER, `${JSON.stringify(ledger, null, 2)}\n`);
}

function featureDocs(ref) {
  const docs = new Map();
  for (const path of run('git', ['ls-tree', '--name-only', ref, 'docs/features/']).split('\n')) {
    const match = /^docs\/features\/(F\d{3})-.+\.md$/.exec(path);
    if (!match) continue;
    if (!docs.has(match[1])) docs.set(match[1], []);
    docs.get(match[1]).push(path);
  }
  return docs;
}

// One list call per UTC day keeps each query small and makes the limit visible.
function listMerged(sinceMs, nowMs) {
  const prs = [];
  const truncatedDays = [];
  for (let day = new Date(sinceMs).setUTCHours(0, 0, 0, 0); day <= nowMs; day += 86400000) {
    const date = new Date(day).toISOString().slice(0, 10);
    const args = ['pr', 'list', '--state', 'merged', '--base', 'main', '--search', `merged:${date}`];
    const chunk = JSON.parse(run('gh', [...args, '--limit', String(LIST_LIMIT), '--json', PR_FIELDS]));
    if (chunk.length >= LIST_LIMIT) truncatedDays.push(date);
    prs.push(...chunk);
  }
  const fresh = prs.filter((pr) => Date.parse(pr.mergedAt) >= sinceMs && !GENERATED_TITLE_RE.test(pr.title));
  return { prs: fresh, truncatedDays };
}

function fetchPr(number) {
  return JSON.parse(run('gh', ['pr', 'view', String(number), '--json', PR_FIELDS]));
}

// Files the merge brought into main (works for squash and merge commits).
function mergedFiles(oid) {
  if (!oid) return [];
  try {
    return run('git', ['diff', '--name-only', `${oid}^1`, oid])
      .split('\n')
      .filter(Boolean)
      .map((path) => ({ path }));
  } catch {
    return [];
  }
}

function docFollowUp(ref, pr, paths) {
  const args = ['log', ref, `--since=${pr.mergedAt}`, '--format=@@COMMIT %h%n%B', '-p', '--unified=0'];
  return docCommitsForPr(run('git', [...args, '--', ...paths]), pr.number, pr.mergeCommit?.oid);
}

// One GraphQL read for the comments of every still-silent PR.
function prComments(numbers) {
  const comments = new Map();
  if (numbers.length === 0) return comments;
  const [owner, name] = run('gh', ['repo', 'view', '--json', 'nameWithOwner', '-q', '.nameWithOwner'])
    .trim()
    .split('/');
  for (let i = 0; i < numbers.length; i += 40) {
    const chunk = numbers.slice(i, i + 40);
    const fields = chunk.map((n) => `p${n}: pullRequest(number: ${n}) { comments(last: 50) { nodes { body } } }`);
    const query = `query { repository(owner: "${owner}", name: "${name}") { ${fields.join(' ')} } }`;
    const repo = JSON.parse(run('gh', ['api', 'graphql', '-f', `query=${query}`])).data.repository;
    for (const n of chunk) comments.set(n, repo[`p${n}`]?.comments?.nodes ?? []);
  }
  return comments;
}

function silentFeatures(ref, pr, link, docs) {
  const files = { files: mergedFiles(pr.mergeCommit?.oid) };
  const silent = [];
  const otherDocCommits = [];
  for (const id of link.features) {
    if (prTouchesFeatureDoc(files, id)) continue;
    const followUp = docFollowUp(ref, pr, docs.get(id));
    if (followUp.provenance.length > 0) continue;
    silent.push(id);
    otherDocCommits.push(...followUp.other);
  }
  return { silent, otherDocCommits };
}

// Without a feature id there is no doc to match, so only a Doc-Sync line or a
// feature doc changed inside the PR settles it.
function unlinkedSilent(pr) {
  return mergedFiles(pr.mergeCommit?.oid).some((file) => file.path.startsWith('docs/features/'))
    ? { silent: [] }
    : { silent: [], unlinked: true };
}

function openInfo(ledger, number) {
  const open = ledger.openPrs[String(number)];
  return open ? { carried: true, firstSeenAt: open.firstSeenAt } : {};
}

function classifyPr(ref, pr, known, docs) {
  const link = linkPrToFeatures(pr, known);
  if (hasDocSyncLine(pr)) return { link, found: { silent: [] }, open: false };
  const found = link.source === 'none' ? unlinkedSilent(pr) : silentFeatures(ref, pr, link, docs);
  return { link, found, open: Boolean(found.unlinked) || found.silent.length > 0 };
}

function evaluatePrs(ref, prs, docs, ledger) {
  const known = new Set(docs.keys());
  const evaluated = new Map();
  const pending = [];
  let linked = 0;
  for (const pr of prs) {
    const { link, found, open } = classifyPr(ref, pr, known, docs);
    if (link.source !== 'none') linked += 1;
    evaluated.set(pr.number, { missing: open, features: found.silent });
    if (open) pending.push({ pr, link, ...found });
  }
  const comments = prComments(pending.map((item) => item.pr.number));
  const missing = [];
  const unlinked = [];
  for (const item of pending) {
    if (hasDocSyncLine({ comments: comments.get(item.pr.number) })) {
      evaluated.set(item.pr.number, { missing: false, features: [] });
      continue;
    }
    const { number, title, mergedAt } = item.pr;
    const base = { number, title, mergedAt, ...openInfo(ledger, number) };
    if (item.unlinked) unlinked.push(base);
    else missing.push({ ...base, ...item.link, features: item.silent, otherDocCommits: item.otherDocCommits });
  }
  return { linked, handled: linked - missing.length, missing, unlinked, evaluated };
}

function backlogFindings(ref, docs, ledger) {
  const rowFile = rowFileAt(ref);
  const rows = parseBacklogRows(run('git', ['show', `${ref}:${rowFile}`]));
  const logArgs = ['log', ref, '--since=180.days', '--format=@@COMMIT %ct', '-p', '--unified=0'];
  const rowChanged = latestChangeByFeature(run('git', [...logArgs, '--', rowFile]), 'backlog');
  const statusChanged = latestChangeByFeature(
    run('git', [...logArgs, '-G', '\\*\\*Status\\*\\*', '--', 'docs/features/']),
    'status',
  );
  const findings = [];
  let disposed = 0;
  for (const row of rows) {
    const path = row.docPath ?? docs.get(row.id)?.[0];
    if (!path) continue;
    const result = rowFinding(ref, row, path, statusChanged.get(row.id) ?? 0, rowChanged.get(row.id) ?? 0);
    if (!result.finding) continue;
    if (result.checkable && rowDisposed(ledger.backlogRows[row.id], row, path, result.docStatus)) disposed += 1;
    else findings.push({ id: row.id, path, ...result.finding });
  }
  return { rows: rows.length, findings, disposed };
}

function rowFinding(ref, row, path, statusAt, rowAt) {
  let docStatus;
  try {
    docStatus = parseStatusLine(run('git', ['show', `${ref}:${path}`]));
  } catch {
    return { finding: { kind: 'backlog-link-missing' }, checkable: false };
  }
  const finding =
    backlogStatusFinding(row, docStatus) ??
    (statusAt > rowAt ? { kind: 'row-older-than-status', statusAt, rowAt } : null);
  return { finding, docStatus, checkable: true };
}

function disposeRow(ref, docs, ledger, id, note) {
  const rowFile = rowFileAt(ref);
  const row = parseBacklogRows(run('git', ['show', `${ref}:${rowFile}`])).find((item) => item.id === id);
  if (!row) throw new Error(`${id} is not an active row in ${rowFile} at ${ref}`);
  const path = row.docPath ?? docs.get(id)?.[0];
  const docStatus = parseStatusLine(run('git', ['show', `${ref}:${path}`])) ?? '';
  ledger.backlogRows[id] = rowDisposition(row, path, docStatus, note.trim(), new Date().toISOString());
  writeLedger(ledger);
  process.stdout.write(
    `Recorded ${id} in docs/ops/doc-sync-dispositions.json; it reopens when the row, its doc link or Status changes.\n`,
  );
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.fetch) run('git', ['fetch', 'origin', 'main', '--quiet']);
  const ledger = readLedger();
  const docs = featureDocs(opts.ref);
  if (opts.disposeRow) return disposeRow(opts.ref, docs, ledger, opts.disposeRow, opts.note);
  const nowMs = Date.now();
  const sinceMs = scanStart(ledger, nowMs, opts.days);
  const window = listMerged(sinceMs, nowMs);
  const inWindow = new Set(window.prs.map((pr) => pr.number));
  const carried = Object.keys(ledger.openPrs)
    .map(Number)
    .filter((n) => !inWindow.has(n))
    .map(fetchPr);
  const prs = evaluatePrs(opts.ref, [...window.prs, ...carried], docs, ledger);
  const report = {
    ref: opts.ref,
    head: run('git', ['rev-parse', '--short=10', opts.ref]).trim(),
    since: new Date(sinceMs).toISOString().slice(0, 16),
    prCount: window.prs.length,
    carriedCount: carried.length,
    truncatedDays: window.truncatedDays,
    prs,
    backlog: backlogFindings(opts.ref, docs, ledger),
  };
  if (opts.updateLedger) {
    ledger.openPrs = nextOpenPrs(ledger.openPrs, prs.evaluated, new Date(nowMs).toISOString());
    // An incomplete list must not move the scan mark past PRs it never saw.
    if (window.truncatedDays.length === 0) ledger.lastScanAt = new Date(nowMs).toISOString();
    writeLedger(ledger);
  }
  const { evaluated, ...publicPrs } = prs;
  const output = { ...report, prs: publicPrs, hasCandidates: hasCandidates(report) };
  process.stdout.write(`${opts.json ? JSON.stringify(output, null, 2) : render(report)}\n`);
}

main();
