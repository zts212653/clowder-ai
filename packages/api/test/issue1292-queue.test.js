it('ordinary and private scheduled producer inputs share successor admission', async (t) => {
  const h = successorFixture(t);
  const delivery = new PersistedQueueDelivery({
    messages: h.messages,
    queue: h.queue,
    progress: async () => 'owned_deferred_busy',
  });
  const deliver = createDeliverFn({
    messageStore: h.messages,
    persistedQueueDelivery: delivery,
    socketManager: { broadcastToRoom() {}, emitToUser() {} },
  });
  const request = {
    threadId: h.threadId,
    userId: 'owner',
    targetCatId: 'opus',
    content: 'scheduled work',
    idempotencyKey: 'scheduled',
  };
  await deliver(request);
  await deliver({ ...request, idempotencyKey: 'scheduled-private', privateContent: 'private work' });
  const rows = await h.ledger.list(h.threadId);
  assert.equal(rows.length, 2);
  assert.ok(rows.every((entry) => entry.targets.length === 1 && entry.targets[0] === 'opus-5'));
});

