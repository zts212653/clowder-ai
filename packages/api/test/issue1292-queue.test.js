it('system pre-resolved private admission persists only the successor and replays its winner', async (t) => {
  const h = successorFixture(t);
  const input = privateInput(h.threadId);
  const result = await h.queue.enqueueDurable(input);
  assert.deepEqual(result.entry.targets, ['opus-5']);
  assert.deepEqual((await h.ledger.list(h.threadId))[0].targets, ['opus-5']);
  getRoster().opus = { ...getRoster().opus, successor: 'codex' };
  const replay = await h.queue.enqueueDurable(input);
  assert.equal(replay.deduped, true);
  assert.deepEqual(replay.entry.targets, ['opus-5']);
  await assert.rejects(h.queue.enqueueDurable({ ...input, targetCats: ['codex'] }), /identity conflict/);
});

it('notice admission and synchronous admission share the same first-write target policy', async (t) => {
  const h = successorFixture(t);
  const input = privateInput(h.threadId);
  const notice = {
    from: input.from,
    userId: 'owner',
    threadId: h.threadId,
    content: 'notice',
    mentions: [],
    timestamp: 1,
    idempotencyKey: 'notice',
  };
  const result = await h.queue.enqueueDurableWithVisibleNotice(input, notice, h.messages);
  assert.deepEqual(result.entry.targets, ['opus-5']);
  getRoster().opus = { ...getRoster().opus, successor: 'codex' };
  const replay = await h.queue.enqueueDurableWithVisibleNotice(input, notice, h.messages);
  assert.equal(replay.deduped, true);
  assert.deepEqual(replay.entry.targets, ['opus-5']);
  const sync = h.queue.enqueueDurableNow({ ...input, idempotencyKey: 'sync' });
  assert.deepEqual(sync.entry.targets, ['codex']);
  assert.throws(
    () => h.queue.enqueueDurableNow({ ...input, idempotencyKey: 'sentinel-sync', targetCats: ['__none__'] }),
    /target/,
  );
});

it('private replay uses the original producer envelope after partial target retirement', async (t) => {
  const h = successorFixture(t);
  const input = privateInput(h.threadId, { targetCats: ['opus', 'codex'] });
  const admitted = await h.queue.enqueueDurable(input);
  await h.ledger.claim(h.threadId, admitted.entry.id, 'partial', Date.now(), 'opus-5');
  await h.ledger.commit(h.threadId, admitted.entry.id, 'partial', 'processing', Date.now());
  const replay = await h.queue.enqueueDurable(input);
  assert.equal(replay.deduped, true);
  assert.deepEqual(replay.entry.targets, ['codex']);
});

for (const legacy of [false, true]) {
  it(`retired ${legacy ? 'legacy' : 'successor'} private receipt replays even after configuration becomes invalid`, async (t) => {
    const h = successorFixture(t);
    const producer = legacy ? new InvocationQueue(h.ledger) : h.queue;
    const input = privateInput(h.threadId, { targetCats: [legacy ? 'codex' : 'opus'] });
    const admitted = await producer.enqueueDurable(input);
    await h.ledger.claim(h.threadId, admitted.entry.id, 'retired', Date.now(), admitted.entry.targets[0]);
    await h.ledger.commit(h.threadId, admitted.entry.id, 'retired', 'processing', Date.now());
    getRoster().opus = { ...getRoster().opus, successor: 'ghost' };
    getRoster().codex = { ...getRoster().codex, available: false };
    const replay = await h.queue.enqueueDurable(input);
    assert.equal(replay.deduped, true);
    assert.deepEqual(replay.entries, []);
    await assert.rejects(h.queue.enqueueDurable({ ...input, content: 'different work' }), /identity conflict/);
    assert.deepEqual(await h.ledger.list(h.threadId), []);
  });
}

