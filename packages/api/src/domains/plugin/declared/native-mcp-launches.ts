import type { NativeMcpServer } from './native-mcp-types.js';

export type { NativeMcpServer } from './native-mcp-types.js';

import { isDeepStrictEqual } from 'node:util';
import type { CapabilityEntry } from '@cat-cafe/shared';
import type {
  InvocationPluginMcpEntry,
  InvocationPluginMcpView,
} from '../../../config/capabilities/invocation-plugin-mcp-view.js';
import { normalizeToolExecutionPolicy } from '../../cats/services/agents/invocation/tool-execution-policy.js';
import type { ToolExecutionPolicy } from '../../cats/services/types.js';
import type { PluginRuntimeAdmission } from '../carrier/runtime-carrier.js';
import { NativePluginActionError, type NativePluginActions } from './native-plugin-actions.js';

export interface DeclaredMcpLaunch {
  readonly contributionId: string;
  readonly server: NativeMcpServer;
  /** Policy generated by the Host's normal installation path, never by a launch descriptor. */
  readonly installationPolicy?: Omit<CapabilityEntry, 'mcpServer' | 'mcpServerOverride'>;
}

interface Activation {
  readonly admission: PluginRuntimeAdmission;
  readonly generation: number;
  readonly launches: readonly DeclaredMcpLaunch[];
}

/** A snapshot resolves only while its original activation and authority remain current. */
export class NativeMcpLaunches {
  readonly #activations = new Map<string, Activation>();

  constructor(
    private readonly admission: (instanceId: string) => Promise<PluginRuntimeAdmission>,
    private readonly actions: NativePluginActions,
  ) {}

  activate(admission: PluginRuntimeAdmission, generation: number, launches: readonly DeclaredMcpLaunch[]): void {
    const instanceId = admission.instance.pluginInstanceId;
    if (this.actions.generation(instanceId) !== generation) throw unavailable();
    this.#activations.set(instanceId, { admission: structuredClone(admission), generation, launches });
  }

  deactivate(instanceId: string): void {
    this.#activations.delete(instanceId);
  }

  deactivateAll(): void {
    this.#activations.clear();
  }

  async resolve(policy: ToolExecutionPolicy): Promise<NativeMcpServer> {
    // Normalize synchronously: the caller cannot replace coordinates across admission's await.
    if (policy.mode !== 'plugin_native') throw unavailable();
    const request = normalizeToolExecutionPolicy(policy);
    if (request.mode !== 'plugin_native') throw unavailable();
    const { pluginInstanceId, contributionId } = request;
    const { activation, current } = await this.currentActivation(pluginInstanceId);

    const declarations = current.packageRecord.manifest.contributions?.filter(
      (item) => item.type === 'mcp' && item.id === contributionId,
    );
    const launches = activation.launches.filter((item) => item.contributionId === contributionId);
    const server = launches[0]?.server;
    if (declarations?.length !== 1 || launches.length !== 1 || !server) throw unavailable();
    const token = server.env.CLOWDER_PLUGIN_ACTION_TOKEN;
    if (!token || this.actions.environment(pluginInstanceId, contributionId).CLOWDER_PLUGIN_ACTION_TOKEN !== token)
      throw unavailable();
    return server;
  }

  /** Ordinary members keep canonical access policy while resolving this Host's local activation. */
  async memberView(localCapabilityRoot?: string): Promise<InvocationPluginMcpView> {
    const entries: InvocationPluginMcpEntry[] = [];
    for (const [instanceId, activation] of [...this.#activations]) {
      let admitted = false;
      try {
        admitted = (await this.currentActivation(instanceId)).activation === activation;
      } catch {
        // Deny only this activation. Retaining its slot prevents a drifted
        // same-plugin instance from silently electing another active instance.
      }
      if (!this.#activations.has(instanceId)) continue;
      for (const launch of activation.launches) {
        const declarations = activation.admission.packageRecord.manifest.contributions?.filter(
          (item) => item.type === 'mcp' && item.id === launch.contributionId,
        );
        entries.push(
          Object.freeze({
            capabilityId: `plugin:${activation.admission.instance.pluginId}:${launch.contributionId}`,
            pluginId: activation.admission.instance.pluginId,
            ...(launch.installationPolicy
              ? { installationPolicy: Object.freeze(structuredClone(launch.installationPolicy)) }
              : {}),
            policySourceRef: `plugin-activation:${instanceId}:${activation.generation}`,
            server: Object.freeze({
              command: launch.server.command,
              args: Object.freeze([...launch.server.args]),
              // Reuse the frozen activation, not a stable namespace that could resolve
              // to a later generation between selection and process startup.
              env: launch.server.env,
              transport: 'stdio' as const,
              workingDir: launch.server.workingDirectory,
            }),
            isCurrent: () =>
              admitted &&
              declarations?.length === 1 &&
              this.#activations.get(instanceId) === activation &&
              this.actions.generation(instanceId) === activation.generation,
          }),
        );
      }
    }
    return Object.freeze({
      entries: Object.freeze(entries),
      ...(localCapabilityRoot ? { localCapabilityRoot } : {}),
    });
  }

  private async currentActivation(
    instanceId: string,
  ): Promise<{ activation: Activation; current: PluginRuntimeAdmission }> {
    const activation = this.#activations.get(instanceId);
    if (!activation) throw unavailable();
    const current = await this.admission(instanceId);
    const original = activation.admission;
    if (
      this.#activations.get(instanceId) !== activation ||
      this.actions.generation(instanceId) !== activation.generation ||
      current.instance.activationState !== 'enabled' ||
      current.instance.lifecycleState !== 'installed' ||
      current.instance.configReadiness !== 'ready' ||
      current.packageRecord.packageState !== 'installed' ||
      current.instance.pluginId !== original.instance.pluginId ||
      current.instance.packageDigest !== original.instance.packageDigest ||
      !isDeepStrictEqual(current.packageRecord, original.packageRecord)
    )
      throw unavailable();
    return { activation, current };
  }
}

function unavailable(): NativePluginActionError {
  return new NativePluginActionError(409, 'Plugin native MCP launch is not current');
}
