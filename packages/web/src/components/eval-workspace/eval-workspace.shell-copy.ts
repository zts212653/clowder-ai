/** Reused evaluation surfaces keep Classic's original Chinese presentation. */
export function useEvalLanguage(): 'zh' | 'en' {
  const language = useShellLanguage();
  const presentation = useShellPresentation();
  return presentation === 'v2' ? language : 'zh';
}
export function useEvalCopy() {
  return evalWorkspaceCopy[useEvalLanguage()];
}
